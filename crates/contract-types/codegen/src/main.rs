//! Generates `crates/contract-types/src/generated/` from the contract's OpenAPI document,
//! `packages/contract/generated/openapi.json`, with progenitor and the typify it embeds
//! (ADR-0003 fixes the wire format):
//! - `types.rs`: every schema as a Rust type (typify), no HTTP dependency;
//! - `client.rs`: the typed HTTP client (progenitor), behind the crate's `client` feature.
//!
//! ```text
//! cargo run -p pulse-contract-codegen --locked             # rewrite generated/
//! cargo run -p pulse-contract-codegen --locked -- --check  # write nothing, exit 1 if it is stale
//! ```
//!
//! The tool owns the whole folder: it deletes any other file there, and `--check` reports one.
//! Every adjustment of the generated code is a generator setting here, never an edit of the
//! output (the edit guard refuses those).

use std::collections::BTreeSet;
use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use progenitor_impl::{GenerationSettings, Generator, TypeImpl};
use schemars::schema::{InstanceType, SchemaObject};

/// The input, relative to the repository root. Slice 1 of T0.4 keeps this name stable.
const OPENAPI_PATH: &str = "packages/contract/generated/openapi.json";
/// The output folder, relative to the repository root.
const OUTPUT_DIR: &str = "crates/contract-types/src/generated";
/// First line of every output file: the edit guard refuses files that carry it (and anything
/// under `generated/`).
const HEADER: &str = "// @generated by `cargo run -p pulse-contract-codegen --locked` from \
                      packages/contract/generated/openapi.json; do not edit.\n\n";
const REGENERATE: &str = "run `cargo run -p pulse-contract-codegen --locked`";

/// One generated file: its name in [`OUTPUT_DIR`] and its content.
#[derive(Debug, PartialEq)]
struct Output {
    name: &'static str,
    content: String,
}

fn main() -> ExitCode {
    let check = std::env::args().skip(1).any(|arg| arg == "--check");
    match run(check) {
        Ok(code) => code,
        Err(error) => {
            report(&format!("pulse-contract-codegen: {error}"));
            ExitCode::FAILURE
        }
    }
}

fn run(check: bool) -> Result<ExitCode, Box<dyn Error>> {
    let root = repository_root();
    let outputs = generate(&read(&root.join(OPENAPI_PATH))?)?;
    let folder = root.join(OUTPUT_DIR);

    if check {
        let stale = stale_files(&folder, &outputs)?;
        if stale.is_empty() {
            return Ok(ExitCode::SUCCESS);
        }
        report(&format!("Stale ({REGENERATE}): {}", stale.join(", ")));
        return Ok(ExitCode::FAILURE);
    }

    fs::create_dir_all(&folder)?;
    for extra in extra_files(&folder, &outputs)? {
        fs::remove_file(folder.join(&extra))?;
        report(&format!("Removed: {OUTPUT_DIR}/{extra}"));
    }
    for output in &outputs {
        fs::write(folder.join(output.name), &output.content)?;
        report(&format!("Wrote: {OUTPUT_DIR}/{}", output.name));
    }
    Ok(ExitCode::SUCCESS)
}

/// The generated files for an OpenAPI 3.0 document: deterministic for a given input and the
/// generator versions pinned in `Cargo.lock`.
fn generate(openapi_json: &str) -> Result<Vec<Output>, Box<dyn Error>> {
    let spec: openapiv3::OpenAPI = serde_json::from_str(openapi_json)?;
    let tokens = Generator::new(&settings()).generate_tokens(&spec)?;
    let (types, client) = split(syn::parse2(tokens)?)?;
    Ok(vec![
        Output {
            name: "types.rs",
            content: render(&types),
        },
        Output {
            name: "client.rs",
            content: render(&client),
        },
    ])
}

/// Positional methods with merged tags (progenitor's defaults: the smallest client), plus:
/// - `PartialEq` on every type, so the core can compare wire values (revisions, snapshots, tests).
/// - Instants and days as `jiff` types instead of chrono: the core does all time math with jiff
///   (spec section 11, `.claude/rules/rust.md`), so the wire types need no conversion and the
///   apps link one date library. Typify matches these schemas ignoring their descriptions.
fn settings() -> GenerationSettings {
    let mut settings = GenerationSettings::default();
    settings
        .with_derive("PartialEq")
        .with_conversion(
            string_format("date-time"),
            "::jiff::Timestamp",
            [TypeImpl::Display, TypeImpl::FromStr].into_iter(),
        )
        .with_conversion(
            string_format("date"),
            "::jiff::civil::Date",
            [TypeImpl::Display, TypeImpl::FromStr].into_iter(),
        );
    settings
}

fn string_format(format: &str) -> SchemaObject {
    SchemaObject {
        instance_type: Some(InstanceType::String.into()),
        format: Some(format.to_owned()),
        ..SchemaObject::default()
    }
}

/// Splits progenitor's single file into the `types` module's content (its outer attributes
/// become inner ones) and everything else, which reaches the types through `crate::types`.
fn split(mut client: syn::File) -> Result<(syn::File, syn::File), Box<dyn Error>> {
    let mut types = None;
    let mut client_items = vec![syn::parse_str::<syn::Item>("use crate::types;")?];
    for item in std::mem::take(&mut client.items) {
        match item {
            syn::Item::Mod(module) if module.ident == "types" => types = Some(module),
            other => client_items.push(other),
        }
    }
    let module = types.ok_or("progenitor's output has no `types` module")?;
    let (_, type_items) = module
        .content
        .ok_or("progenitor's `types` module has no body")?;
    let mut types: syn::File = syn::parse_str("")?;
    types.attrs = module
        .attrs
        .into_iter()
        .map(|mut attr| {
            attr.style = syn::AttrStyle::Inner(syn::token::Not::default());
            attr
        })
        .collect();
    types.items = type_items;
    client.items = client_items;
    Ok((types, client))
}

fn render(file: &syn::File) -> String {
    format!("{HEADER}{}", prettyplease::unparse(file))
}

/// Output files whose committed content differs, plus files the tool would delete.
fn stale_files(folder: &Path, outputs: &[Output]) -> Result<Vec<String>, Box<dyn Error>> {
    let mut stale: Vec<String> = outputs
        .iter()
        .filter(|output| {
            fs::read_to_string(folder.join(output.name)).ok().as_deref() != Some(&*output.content)
        })
        .map(|output| output.name.to_owned())
        .collect();
    stale.extend(extra_files(folder, outputs)?);
    Ok(stale)
}

/// Files in the output folder that the generator does not write.
fn extra_files(folder: &Path, outputs: &[Output]) -> Result<Vec<String>, Box<dyn Error>> {
    if !folder.exists() {
        return Ok(Vec::new());
    }
    let expected: BTreeSet<&str> = outputs.iter().map(|output| output.name).collect();
    let mut extra = Vec::new();
    for entry in fs::read_dir(folder)? {
        let name = entry?.file_name().to_string_lossy().into_owned();
        if !expected.contains(name.as_str()) {
            extra.push(name);
        }
    }
    extra.sort();
    Ok(extra)
}

/// `crates/contract-types/codegen` is three levels below the root.
fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..")
}

fn read(path: &Path) -> Result<String, Box<dyn Error>> {
    fs::read_to_string(path)
        .map_err(|error| format!("cannot read {}: {error}", path.display()).into())
}

#[allow(
    clippy::print_stderr,
    reason = "a command-line tool reports to the terminal"
)]
fn report(message: &str) {
    eprintln!("{message}");
}

#[cfg(test)]
mod tests {
    use super::{OPENAPI_PATH, OUTPUT_DIR, Output, generate, read, repository_root, stale_files};

    fn generated() -> Vec<Output> {
        generate(&read(&repository_root().join(OPENAPI_PATH)).unwrap()).unwrap()
    }

    fn content(name: &str) -> String {
        generated()
            .into_iter()
            .find(|output| output.name == name)
            .unwrap()
            .content
    }

    #[test]
    fn committed_output_matches_the_contract() {
        let stale = stale_files(&repository_root().join(OUTPUT_DIR), &generated()).unwrap();

        assert!(
            stale.is_empty(),
            "stale in {OUTPUT_DIR}: {stale:?}; {}",
            super::REGENERATE
        );
    }

    #[test]
    fn the_check_reports_a_changed_byte_a_missing_file_and_an_extra_file() {
        let folder =
            std::env::temp_dir().join(format!("pulse-codegen-check-{}", std::process::id()));
        std::fs::create_dir_all(&folder).unwrap();
        let outputs = [
            Output {
                name: "types.rs",
                content: "// @generated\nstruct A;\n".to_owned(),
            },
            Output {
                name: "client.rs",
                content: "// @generated\n".to_owned(),
            },
        ];
        std::fs::write(folder.join("types.rs"), "// @generated\nstruct B;\n").unwrap();
        std::fs::write(folder.join("api.rs"), "// @generated\n").unwrap();

        let stale = stale_files(&folder, &outputs);
        std::fs::remove_dir_all(&folder).unwrap();

        assert_eq!(stale.unwrap(), ["types.rs", "client.rs", "api.rs"]);
    }

    #[test]
    fn generation_is_deterministic() {
        assert_eq!(generated(), generated());
    }

    #[test]
    fn every_file_starts_with_the_generated_marker() {
        for output in generated() {
            assert!(
                output.content.starts_with("// @generated "),
                "{}",
                output.name
            );
        }
    }

    #[test]
    fn instants_and_days_use_jiff_not_chrono() {
        let types = content("types.rs");

        assert!(types.contains("::jiff::Timestamp"));
        assert!(types.contains("::jiff::civil::Date"));
        assert!(
            generated()
                .iter()
                .all(|output| !output.content.contains("chrono"))
        );
    }

    #[test]
    fn the_types_do_not_depend_on_the_http_client() {
        let types = content("types.rs");

        assert!(!types.contains("progenitor_client"));
        assert!(!types.contains("reqwest"));
    }
}
