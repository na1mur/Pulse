// Builds the OpenAPI 3.0.3 document from the catalogue. 3.0 rather than 3.1 because progenitor
// (the Rust client generator) reads OpenAPI 3.0.x only; ADR 0003.
import { z } from 'zod';
import {
  errorCodesOf,
  httpOperations,
  operations,
  successStatusOf,
  type HttpOperation,
} from '../catalogue.js';
import { ERROR_HTTP_STATUS } from '../errors.js';
import { RESPONSE_HEADERS } from '../http.js';
import { cleanSchema, componentNameOf, toJsonSchemas, type Json } from './components.js';

const SCHEMAS = '#/components/schemas/';
const ref = (name: string) => ({ $ref: `${SCHEMAS}${name}` });

function componentRef(schema: z.ZodType, what: string) {
  const name = componentNameOf(schema);
  if (!name) throw new Error(`${what} must be an exported contract schema`);
  return ref(name);
}

function operationId(name: string): string {
  return name.replace(/\.(\w)/g, (_, letter: string) => letter.toUpperCase());
}

function parameters(op: HttpOperation): Json[] {
  const located = [
    ['path', op.params],
    ['query', op.query],
  ] as const;
  return located.flatMap(([location, object]) =>
    Object.entries(object?.shape ?? {}).map(([name, field]: [string, z.ZodType]) => {
      const optional = field instanceof z.ZodOptional;
      const inner = optional ? (field.unwrap() as z.ZodType) : field;
      const component = componentNameOf(inner);
      // Output mode: a query integer is parsed from URL text, so it is described as an integer.
      const schema = component
        ? ref(component)
        : cleanSchema(
            z.toJSONSchema(inner, {
              target: 'openapi-3.0',
              io: 'output',
              unrepresentable: 'throw',
            }) as Json,
          );
      return { name, in: location, required: !optional, schema };
    }),
  );
}

const responseHeaders = Object.fromEntries(
  Object.keys(RESPONSE_HEADERS).map((name) => [name, { $ref: `#/components/headers/${name}` }]),
);

function responses(op: HttpOperation): Record<string, Json> {
  const status = successStatusOf(op);
  const success: Record<string, Json> = {
    description: status === 204 ? 'Done' : 'OK',
    headers: responseHeaders,
  };
  if (op.response) {
    success['content'] = {
      'application/json': { schema: componentRef(op.response, 'A response') },
    };
  }
  const result: Record<string, Json> = { [status]: success };
  for (const code of errorCodesOf(op)) {
    result[ERROR_HTTP_STATUS[code]] = {
      description: code,
      headers: responseHeaders,
      content: { 'application/json': { schema: ref('ErrorBody') } },
    };
  }
  return result;
}

function pathOperation(name: string, op: HttpOperation): Record<string, Json> {
  const operation: Record<string, Json> = {
    operationId: operationId(name),
    'x-pulse-operation': name,
    tags: [op.group],
    summary: op.summary,
  };
  const parameterList = parameters(op);
  if (parameterList.length > 0) operation['parameters'] = parameterList;
  if (op.body) {
    operation['requestBody'] = {
      required: true,
      content: { 'application/json': { schema: componentRef(op.body, 'A request body') } },
    };
  }
  operation['responses'] = responses(op);
  if (op.auth === 'user') operation['security'] = [{ bearerAuth: [] }];
  return operation;
}

export function buildOpenApiDocument(io: 'input' | 'output' = 'input') {
  const paths: Record<string, Record<string, Json>> = {};
  for (const [name, op] of httpOperations()) {
    paths[op.path] = { ...paths[op.path], [op.method.toLowerCase()]: pathOperation(name, op) };
  }
  const pendingOperations = Object.entries(operations).flatMap(([name, op]) =>
    op.kind === 'pending'
      ? [
          {
            name,
            group: op.group,
            summary: op.summary,
            definedBy: op.definedBy,
            priority: op.priority,
          },
        ]
      : [],
  );
  const realtime = operations['sync.subscribe'];
  return {
    openapi: '3.0.3',
    info: {
      title: 'Pulse API',
      version: '1.0.0',
      description:
        '@generated by `pnpm --filter @pulse/contract generate` from packages/contract/src; do not edit.',
    },
    paths,
    components: {
      schemas: toJsonSchemas('openapi-3.0', SCHEMAS, io),
      headers: Object.fromEntries(
        Object.entries(RESPONSE_HEADERS).map(([name, header]) => [
          name,
          { description: header.description, required: true, schema: header.schema },
        ]),
      ),
      securitySchemes: { bearerAuth: { type: 'http', scheme: 'bearer' } },
    },
    'x-pulse-realtime': {
      path: realtime.path,
      clientMessage: componentRef(realtime.clientMessage, 'The client message'),
      serverMessage: componentRef(realtime.serverMessage, 'The server message'),
    },
    'x-pulse-pending-operations': pendingOperations,
  };
}
