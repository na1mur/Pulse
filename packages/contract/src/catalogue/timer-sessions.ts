// Timer and Sessions group operations (spec 7.2).
import { Session, TimerState } from '../entities.js';
import * as timer from '../operations/timer-sessions.js';
import { http, pending } from '../operation.js';

export const timerAndSessionOperations = {
  'timer.get': http({
    group: 'timer',
    summary: 'The running session, if any.',
    method: 'GET',
    path: '/v1/timer',
    auth: 'user',
    response: TimerState,
    errors: [],
  }),
  'timer.start': http({
    group: 'timer',
    summary: 'Start a session; while one runs, return it unchanged (R-01, R-02).',
    method: 'POST',
    path: '/v1/timer/start',
    auth: 'user',
    body: timer.StartTimerRequest,
    response: timer.TimerResult,
    errors: ['NOT_FOUND', 'CONFLICT'],
  }),
  'timer.pause': http({
    group: 'timer',
    summary: 'End the running session at the press; a no-op while idle (R-02, R-06).',
    method: 'POST',
    path: '/v1/timer/pause',
    auth: 'user',
    body: timer.PauseTimerRequest,
    response: timer.PauseTimerResult,
    errors: [],
  }),
  'timer.updateRunning': http({
    group: 'timer',
    summary: "Change the running session's title or tag (TIM-02).",
    method: 'POST',
    path: '/v1/timer/update',
    auth: 'user',
    body: timer.UpdateRunningRequest,
    response: timer.TimerResult,
    errors: ['NOT_FOUND'],
  }),
  'timer.switch': pending(
    'timer',
    'End the running session and start another (R-02).',
    'TIM-05',
    'P2',
  ),
  'timer.discard': pending('timer', 'Discard the running session (R-08).', 'TIM-06', 'P2'),
  'sessions.list': http({
    group: 'sessions',
    summary: 'Sessions of a range of days, filtered and searched, newest first (LOG-06).',
    method: 'GET',
    path: '/v1/sessions',
    auth: 'user',
    query: timer.ListSessionsQuery,
    response: timer.SessionPage,
    errors: [],
  }),
  'sessions.get': http({
    group: 'sessions',
    summary: 'One session.',
    method: 'GET',
    path: '/v1/sessions/{sessionId}',
    auth: 'user',
    params: timer.SessionParams,
    response: Session,
    errors: ['NOT_FOUND'],
  }),
  'sessions.create': http({
    group: 'sessions',
    summary: 'Add a past session manually; an overlap is CONFLICT (LOG-05, R-05).',
    method: 'POST',
    path: '/v1/sessions',
    auth: 'user',
    body: timer.CreateSessionRequest,
    response: timer.SessionResult,
    errors: ['NOT_FOUND', 'CONFLICT'],
  }),
  'sessions.update': http({
    group: 'sessions',
    summary: 'Edit title, tag, summary, start or end; an overlap is CONFLICT (LOG-03, R-05).',
    method: 'POST',
    path: '/v1/sessions/{sessionId}/update',
    auth: 'user',
    params: timer.SessionParams,
    body: timer.UpdateSessionRequest,
    response: timer.SessionResult,
    errors: ['NOT_FOUND', 'CONFLICT'],
  }),
  'sessions.delete': http({
    group: 'sessions',
    summary: 'Delete a session (LOG-04).',
    method: 'POST',
    path: '/v1/sessions/{sessionId}/delete',
    auth: 'user',
    params: timer.SessionParams,
    body: timer.DeleteSessionRequest,
    response: timer.DeleteSessionResult,
    errors: ['NOT_FOUND'],
  }),
} as const;
